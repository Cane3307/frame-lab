#!/usr/bin/env python3
"""Build the browser catalog from the untouched skill JSON, using only stdlib."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "short-video-lab" / "references"
DESTINATION = ROOT / "data" / "catalog.js"
THEMES = ["曬過程", "說故事", "教知識", "熬雞湯", "選立場", "賣商品", "演劇情"]
FORMS = ["切片", "口播", "圖片旁白", "影片旁白", "情境劇"]
HEADLINES = ["新知式", "提問式", "解答式", "反常式", "佔便宜", "揭秘式"]


def read_json(filename):
    return json.loads((SOURCE / filename).read_text(encoding="utf-8"))


def build():
    combinations = sorted(
        [row for path in SOURCE.glob("catalog-*.json") for row in read_json(path.name)],
        key=lambda row: row["id"],
    )
    formulas = read_json("formulas.json")
    mixes = read_json("mixes.json")
    groups = {"combinations": combinations, "formulas": formulas, "mixes": mixes}
    expected_counts = {"combinations": 210, "formulas": 12, "mixes": 31}
    for name, records in groups.items():
        assert len(records) == expected_counts[name], f"Unexpected {name} count"
        assert len({row["id"] for row in records}) == len(records), f"Duplicate {name} ID"
        for row in records:
            assert len(row["examples"]) == 2, f"{row['id']}: expected two examples"
            assert all(example["evidence_status"] == "虛構教學示例" for example in row["examples"])

    expected_ids = {f"C{i:03d}" for i in range(1, 211)}
    assert {row["id"] for row in combinations} == expected_ids
    assert {row["id"] for row in formulas} == {f"F{i:02d}" for i in range(1, 13)}
    assert {row["id"] for row in mixes} == (
        {f"M{i:02d}" for i in range(1, 22)} | {f"P{i:02d}" for i in range(1, 11)}
    )
    expected_keys = {(theme, form, headline) for theme in THEMES for form in FORMS for headline in HEADLINES}
    actual_keys = [(row["theme"], row["form"], row["headline"]) for row in combinations]
    assert len(set(actual_keys)) == len(actual_keys), "Duplicate combination"
    assert set(actual_keys) == expected_keys, "Missing classification combination"
    for row in combinations:
        expected_number = 1 + THEMES.index(row["theme"]) * 30 + FORMS.index(row["form"]) * 6 + HEADLINES.index(row["headline"])
        assert row["id"] == f"C{expected_number:03d}", f"{row['id']}: ID/category mismatch"

    data = {
        **groups,
        "meta": {
            "version": "1.0",
            "language": "zh-Hant",
            "source": "short-video-lab/references/*.json",
            "evidence_status": "虛構教學示例",
            "notice": "分析模板與虛構教學示例；不是實測、顧客見證或成效保證。",
            "themes": THEMES,
            "forms": FORMS,
            "headlines": HEADLINES,
            "counts": {
                **{name: len(records) for name, records in groups.items()},
                "examples": sum(len(row["examples"]) for rows in groups.values() for row in rows),
            },
        },
    }
    # A classic script supports both file:// previews and GitHub Pages, with no fetch or build runtime.
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    payload = payload.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029").replace("</", "<\\/")
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    DESTINATION.write_text(
        "// Generated by scripts/build-catalog.py. Edit the original skill JSON to update.\n"
        + "window.LAB_DATA = " + payload + ";\n",
        encoding="utf-8",
    )
    print(json.dumps({"output": str(DESTINATION), "checks": "PASS", "counts": data["meta"]["counts"], "unique_combinations": len(set(actual_keys)), "all_ids_unique": len({row["id"] for rows in groups.values() for row in rows}) == sum(map(len, groups.values()))}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    build()
